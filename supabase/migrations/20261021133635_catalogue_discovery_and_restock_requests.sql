create table public.restock_requests (
  id integer generated by default as identity primary key,
  product_id integer not null references public.products(id) on delete cascade,
  pos_code text not null,
  product_code text not null,
  color_name text not null,
  size text,
  contact_type text not null check (contact_type in ('email', 'phone')),
  contact text not null check (length(contact) between 3 and 254),
  client_key text not null,
  status text not null default 'pending' check (status in ('pending', 'contacted')),
  created_at timestamptz not null default now(),
  contacted_at timestamptz
);
create unique index restock_requests_pending_unique on public.restock_requests(pos_code, contact_type, contact) where status = 'pending';
create index restock_requests_queue_idx on public.restock_requests(status, created_at, id);
create index restock_requests_client_idx on public.restock_requests(client_key, created_at);
create index restock_requests_product_idx on public.restock_requests(product_id);
alter table public.restock_requests enable row level security;
revoke all on public.restock_requests from public, anon, authenticated;
revoke all on sequence public.restock_requests_id_seq from public, anon, authenticated;
grant select, insert, update, delete on public.restock_requests to service_role;
grant usage, select on sequence public.restock_requests_id_seq to service_role;

-- Server-only: the public API validates contact details and explicit consent first.
create function public.request_restock(p_variant_id integer, p_contact_type text, p_contact text, p_client_key text)
returns text language plpgsql security invoker set search_path = public, pg_temp as $$
declare
  requested record;
begin
  if p_client_key is null or length(p_client_key) < 32 then raise exception 'Invalid client key'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_client_key, 0));
  select v.*, p.cleaned_code, p.lifecycle_status, coalesce(c.english_name, 'One Color') as color_name
    into requested from public.variants v
    join public.products p on p.id = v.product_id
    join public.categories category on category.id = p.category_id and category.is_visible
    left join public.colors c on c.id = v.color_id
    where v.id = p_variant_id and v.is_visible and p.is_published and p.lifecycle_status <> 'discontinued';
  if not found then return 'unavailable'; end if;
  if requested.lifecycle_status = 'active' and requested.stock_quantity > 0 then return 'in_stock'; end if;
  if exists (select 1 from public.restock_requests where pos_code = requested.pos_code and contact_type = p_contact_type and contact = p_contact and status = 'pending') then return 'saved'; end if;
  if (select count(*) from public.restock_requests where client_key = p_client_key and created_at > now() - interval '1 hour') >= 5 then return 'limited'; end if;
  insert into public.restock_requests(product_id, pos_code, product_code, color_name, size, contact_type, contact, client_key)
    values (requested.product_id, requested.pos_code, requested.cleaned_code, requested.color_name, requested.size, p_contact_type, p_contact, p_client_key)
    on conflict (pos_code, contact_type, contact) where status = 'pending' do nothing;
  return 'saved';
end;
$$;
revoke all on function public.request_restock(integer, text, text, text) from public, anon, authenticated;
grant execute on function public.request_restock(integer, text, text, text) to service_role;
